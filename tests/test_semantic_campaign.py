"""Independent scalar contracts for the bounded semantic campaign.

The checked-in expectations are hand-calculated; neither the portable VM nor
the campaign oracle generated them. They intentionally distinguish exact first
errors and Bool/I64 tags, including admission order, fused operand charging,
lazy Boolean arms, branch joins and return admission. Native execution of this
same corpus is a separate campaign gate; these tests do not claim JIT coverage.
"""
from copy import deepcopy
import json
from pathlib import Path
import sys
import tempfile
import unittest
from unittest.mock import patch


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import semantic_campaign as campaign


FIXTURES = ROOT / "tests" / "fixtures" / "semantic-campaign" / "cases.json"
MIN_I64 = -(1 << 63)
MAX_I64 = (1 << 63) - 1
ARITHMETIC = "invalid or overflowing integer arithmetic"
UNINITIALIZED = "read of uninitialized local"
FUEL = "module instruction budget exhausted"
CELLS = "module cell budget exhausted"
FRAMES = "module frame limit exceeded"


def literal(value):
    return {"op": "int", "value": value}


def simple_program():
    return {
        "params": [], "locals": [], "result": "int",
        "body": [{"op": "return", "value": literal(7)}],
    }


def raw_fixtures():
    return json.loads(FIXTURES.read_text(encoding="utf-8"))


class FixedSemanticContracts(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.document = raw_fixtures()
        cls.cases = cls.document["cases"]
        cls.by_id = {case["id"]: case for case in cls.cases}

    def test_fixture_inventory_is_independent_and_complete(self):
        self.assertEqual(self.document["schema"], "fluxr-semantic-fixtures-v1")
        self.assertEqual(len(self.cases), 28)
        self.assertEqual(len(self.by_id), len(self.cases))
        self.assertEqual(sum(len(case["calls"]) for case in self.cases), 182)
        self.assertEqual(campaign.load_fixtures(FIXTURES), self.cases)
        for case in self.cases:
            with self.subTest(case=case["id"]):
                self.assertEqual(len(case["calls"]), len(case["expected"]))
                self.assertIsNone(campaign.validate_program(case["program"]))

    def test_every_hand_calculated_outcome_matches_independent_oracle(self):
        for case in self.cases:
            for index, (call, expected) in enumerate(zip(case["calls"], case["expected"])):
                with self.subTest(case=case["id"], call=index, limits=call["limits"]):
                    actual = campaign.oracle(case["program"], call)
                    self.assertEqual(set(actual), {"outcome", "witness"})
                    self.assertTrue(
                        campaign.compare_outcome(expected, actual["outcome"]),
                        f"expected {expected!r}, actual {actual!r}",
                    )
                    self.assertIsInstance(actual["witness"], dict)

    def test_division_and_remainder_use_truncation_toward_zero(self):
        # Python // and % by themselves would fail these signed examples.
        for ident, values in (
            ("signed_div", [-2, -2, 2]),
            ("signed_rem", [-1, 1, -1]),
        ):
            case = self.by_id[ident]
            for call, expected_value in zip(case["calls"], values):
                with self.subTest(case=ident, arguments=call["arguments"]):
                    self.assertEqual(
                        campaign.oracle(case["program"], call)["outcome"],
                        {"value": {"i64": expected_value}},
                    )

    def test_minimum_divided_or_remainder_by_negative_one_both_trap(self):
        for ident in ("signed_div", "signed_rem"):
            case = self.by_id[ident]
            call = next(call for call in case["calls"]
                        if call["arguments"] == [{"i64": MIN_I64}, {"i64": -1}])
            with self.subTest(case=ident):
                self.assertEqual(campaign.oracle(case["program"], call)["outcome"],
                                 {"trap": ARITHMETIC})

    def test_atomic_operand_charge_and_nested_evaluation_are_distinct(self):
        # These fixed outcomes are not generated by changing an oracle flag.
        # An atomic add costs three before either local is read; a nested add
        # must read its left local before beginning its right division.
        expectations = {
            "atomic_binary_debit_before_uninitialized": [FUEL, FUEL, FUEL, UNINITIALIZED],
            "left_uninitialized_beats_right_arithmetic": [FUEL, UNINITIALIZED, UNINITIALIZED, UNINITIALIZED],
            "left_arithmetic_beats_right_uninitialized": [FUEL, FUEL, ARITHMETIC, ARITHMETIC],
        }
        for ident, expected in expectations.items():
            case = self.by_id[ident]
            for call, message in zip(case["calls"], expected):
                with self.subTest(case=ident, limits=call["limits"]):
                    self.assertEqual(campaign.oracle(case["program"], call)["outcome"],
                                     {"trap": message})

    def test_lazy_boolean_paths_skip_the_entire_unselected_expression(self):
        for ident, short_value in (("and_skips_arithmetic_trap", False),
                                   ("or_skips_arithmetic_trap", True)):
            case = self.by_id[ident]
            with self.subTest(case=ident):
                self.assertEqual(campaign.oracle(case["program"], case["calls"][0])["outcome"],
                                 {"value": {"bool": short_value}})
                self.assertEqual(campaign.oracle(case["program"], case["calls"][1])["outcome"],
                                 {"trap": ARITHMETIC})

    def test_outcome_comparison_is_exact_in_tag_value_and_first_error(self):
        equal = [
            ({"value": {"i64": MIN_I64}}, {"value": {"i64": MIN_I64}}),
            ({"value": {"i64": MAX_I64}}, {"value": {"i64": MAX_I64}}),
            ({"value": {"bool": True}}, {"value": {"bool": True}}),
            ({"trap": ARITHMETIC}, {"trap": ARITHMETIC}),
        ]
        unequal = [
            ({"value": {"bool": True}}, {"value": {"i64": 1}}),
            ({"value": {"i64": 1}}, {"value": {"i64": True}}),
            ({"value": {"bool": False}}, {"value": {"bool": 0}}),
            ({"value": {"i64": 1}}, {"value": {"i64": 2}}),
            ({"trap": ARITHMETIC}, {"trap": UNINITIALIZED}),
            ({"trap": FUEL}, {"trap": CELLS}),
            ({"trap": CELLS}, {"trap": FRAMES}),
            ({"trap": ARITHMETIC}, {"trap": ARITHMETIC + " "}),
            ({"trap": ARITHMETIC}, {"value": {"i64": 0}}),
        ]
        for expected, observed in equal:
            with self.subTest(expected=expected, observed=observed):
                self.assertTrue(campaign.compare_outcome(expected, observed))
        for expected, observed in unequal:
            with self.subTest(expected=expected, observed=observed):
                self.assertFalse(campaign.compare_outcome(expected, observed))


class ProgramAndFixtureAdmission(unittest.TestCase):
    def assert_invalid_program(self, program):
        with self.assertRaises(ValueError):
            campaign.validate_program(program)

    def test_declared_types_and_names_are_checked_before_emission(self):
        variants = []
        p = simple_program()
        p["params"] = [{"name": "x", "type": "int"}, {"name": "x", "type": "int"}]
        variants.append(p)
        p = simple_program()
        p["params"] = [{"name": "x", "type": "int"}]
        p["locals"] = [{"name": "x", "type": "int"}]
        variants.append(p)
        p = simple_program()
        p["params"] = [{"name": "x", "type": "u64"}]
        variants.append(p)
        p = simple_program()
        p["params"] = [{"name": "x) (ret 9)", "type": "int"}]
        variants.append(p)
        p = simple_program()
        # The compact reader treats bare unit as a literal, never a variable.
        p["params"] = [{"name": "unit", "type": "int"}]
        p["body"][0]["value"] = {"op": "var", "name": "unit"}
        variants.append(p)
        p = simple_program()
        p["body"][0]["value"] = {"op": "var", "name": "missing"}
        variants.append(p)
        p = simple_program()
        p["body"].insert(0, {"op": "set", "name": "missing", "value": literal(1)})
        variants.append(p)
        p = simple_program()
        p["body"][0]["value"] = {"op": "add", "left": {"op": "bool", "value": True},
                                  "right": literal(1)}
        variants.append(p)
        p = simple_program()
        p["body"].insert(0, {"op": "if", "condition": literal(1), "then": [], "else": []})
        variants.append(p)
        p = simple_program()
        p["result"] = "bool"
        variants.append(p)
        for index, program in enumerate(variants):
            with self.subTest(index=index):
                self.assert_invalid_program(program)

    def test_integer_bool_and_integer_range_are_separate(self):
        for value in (True, False, MIN_I64 - 1, MAX_I64 + 1, 1.0, "1", None):
            p = simple_program()
            p["body"][0]["value"] = literal(value)
            with self.subTest(value=value):
                self.assert_invalid_program(p)
        for value in (0, 1, "false", None):
            p = simple_program()
            p["result"] = "bool"
            p["body"][0]["value"] = {"op": "bool", "value": value}
            with self.subTest(bool_value=value):
                self.assert_invalid_program(p)

    def test_campaign_subset_rejects_unbounded_or_unmodelled_constructs(self):
        variants = []
        p = simple_program()
        p["body"].insert(0, {"op": "while", "condition": {"op": "bool", "value": True}, "body": []})
        variants.append(p)
        p = simple_program()
        p["body"][0]["value"] = {"op": "call", "name": "calc", "arguments": []}
        variants.append(p)
        p = simple_program()
        p["body"][0]["value"] = {"op": "shl", "left": literal(1), "right": literal(63)}
        variants.append(p)
        p = simple_program()
        p["body"].append({"op": "return", "value": literal(1)})
        variants.append(p)
        p = simple_program()
        p["body"].insert(0, {"op": "if", "condition": {"op": "bool", "value": True},
                             "then": [{"op": "return", "value": literal(1)}], "else": []})
        variants.append(p)
        p = simple_program()
        p["body"] = []
        variants.append(p)
        p = simple_program()
        p["result"] = "bool"
        expr = {"op": "bool", "value": False}
        for _ in range(100):
            expr = {"op": "not", "value": expr}
        p["body"][0]["value"] = expr
        variants.append(p)
        for index, program in enumerate(variants):
            with self.subTest(index=index):
                self.assert_invalid_program(program)

    def test_malformed_statement_containers_fail_as_input_errors(self):
        for body in ([None], [7], ["return"], [[]], {}, None):
            program = simple_program()
            program["body"] = body
            with self.subTest(body=body):
                self.assert_invalid_program(program)

    def test_fixture_loader_rejects_duplicate_json_fields(self):
        with tempfile.TemporaryDirectory(prefix="semantic-fixture-") as directory:
            path = Path(directory) / "duplicate.json"
            path.write_text('{"schema":"fluxr-semantic-fixtures-v1","cases":[],"cases":[]}',
                            encoding="utf-8")
            with self.assertRaises(ValueError):
                campaign.load_fixtures(path)

    def test_strict_json_rejects_nonfinite_literals_and_finite_spelling_overflow(self):
        # parse_constant alone does not reject a legal JSON exponent that
        # overflows Python's binary64 decoder to positive/negative infinity.
        for number in (b"NaN", b"Infinity", b"-Infinity", b"1e999", b"-1e999"):
            with self.subTest(number=number):
                with self.assertRaises(campaign.CampaignError):
                    campaign.strict_json(b'{"number":' + number + b'}')
        self.assertEqual(campaign.strict_json(b'{"number":1.25}'), {"number": 1.25})

    def test_fixture_loader_rejects_mismatched_expected_count(self):
        document = raw_fixtures()
        document["cases"][0]["expected"].pop()
        with tempfile.TemporaryDirectory(prefix="semantic-fixture-") as directory:
            path = Path(directory) / "missing-expectation.json"
            path.write_text(json.dumps(document), encoding="utf-8")
            with self.assertRaises(ValueError):
                campaign.load_fixtures(path)

    def test_fixture_loader_preserves_pinned_expectations(self):
        # Loading must never turn a modified golden into a newly computed one.
        # A loader may reject a wrong pin or retain it for the comparison gate.
        document = raw_fixtures()
        document["cases"][0]["expected"][0] = {"value": {"i64": 12345}}
        with tempfile.TemporaryDirectory(prefix="semantic-fixture-") as directory:
            path = Path(directory) / "altered-expectation.json"
            path.write_text(json.dumps(document), encoding="utf-8")
            try:
                cases = campaign.load_fixtures(path)
            except ValueError:
                return
            self.assertEqual(cases[0]["expected"][0], {"value": {"i64": 12345}})
            self.assertFalse(campaign.compare_outcome(
                cases[0]["expected"][0],
                campaign.oracle(cases[0]["program"], cases[0]["calls"][0])["outcome"],
            ))


class SeededGeneration(unittest.TestCase):
    def test_generator_refuses_invalid_seed_count_depth_and_call_bounds(self):
        configurations = [
            (-1, 1, 0, 1), (1 << 64, 1, 0, 1), (True, 1, 0, 1),
            (0, 0, 0, 1), (0, 257, 0, 1), (0, True, 0, 1),
            (0, 1, -1, 1), (0, 1, 7, 1), (0, 1, False, 1),
            (0, 1, 0, 0), (0, 1, 0, 33), (0, 1, 0, True),
        ]
        for seed, count, depth, calls in configurations:
            with self.subTest(seed=seed, count=count, depth=depth, calls=calls):
                with self.assertRaises(ValueError):
                    campaign.generate_cases(seed, count, max_depth=depth, calls_per_case=calls)

    def test_maximum_program_count_and_expression_depth_are_admitted(self):
        cases = campaign.generate_cases(MAX_I64, 256, max_depth=6, calls_per_case=1)
        self.assertEqual(len(cases), 256)
        for case in cases:
            with self.subTest(case=case["id"]):
                self.assertIsNone(campaign.validate_program(case["program"]))
                self.assertEqual(len(case["calls"]), 1)

    def test_seed_reproduces_programs_calls_and_emitted_sources(self):
        first = campaign.generate_cases(0x243, 32, max_depth=4, calls_per_case=8)
        second = campaign.generate_cases(0x243, 32, max_depth=4, calls_per_case=8)
        self.assertEqual(first, second)
        self.assertEqual(len(first), 32)
        self.assertEqual(len({case["id"] for case in first}), 32)
        self.assertTrue(all(len(case["calls"]) == 8 for case in first))
        self.assertTrue(all("expected" not in case for case in first))
        self.assertEqual([campaign.emit_source(case["program"]) for case in first],
                         [campaign.emit_source(case["program"]) for case in second])
        self.assertNotEqual(first, campaign.generate_cases(0x244, 32, max_depth=4, calls_per_case=8))

    def test_generated_programs_are_valid_and_results_remain_tagged_scalars(self):
        for case in campaign.generate_cases(0xDEADBEEF, 48, max_depth=4, calls_per_case=8):
            with self.subTest(case=case["id"]):
                original = deepcopy(case)
                self.assertIsNone(campaign.validate_program(case["program"]))
                source = campaign.emit_source(case["program"])
                self.assertIsInstance(source, str)
                self.assertTrue(source.startswith("v2"))
                self.assertLessEqual(len(source.encode("utf-8")), 256 * 1024)
                for call in case["calls"]:
                    outcome = campaign.oracle(case["program"], call)["outcome"]
                    self.assertIn(set(outcome), ({"value"}, {"trap"}))
                    if "value" in outcome:
                        value = outcome["value"]
                        self.assertEqual(len(value), 1)
                        if "i64" in value:
                            self.assertIs(type(value["i64"]), int)
                            self.assertGreaterEqual(value["i64"], MIN_I64)
                            self.assertLessEqual(value["i64"], MAX_I64)
                        else:
                            self.assertEqual(set(value), {"bool"})
                            self.assertIs(type(value["bool"]), bool)
                    else:
                        self.assertIsInstance(outcome["trap"], str)
                        self.assertTrue(outcome["trap"])
                self.assertEqual(case, original, "validation/emission/oracle mutated a replay input")


class ExactFailureSensitivity(unittest.TestCase):
    def test_reduction_signature_distinguishes_exact_first_trap_pair(self):
        def signature(expected, observed, kind="trap"):
            report = {"mismatches": [{
                "case": "first-error", "call": 0, "backend": "prepared", "kind": kind,
                "expected": expected, "observed": observed,
            }]}
            return campaign.failure_signature(report, "first-error", 0)

        original = signature({"trap": UNINITIALIZED}, {"trap": ARITHMETIC})
        self.assertNotEqual(original, signature({"trap": UNINITIALIZED}, {"trap": FUEL}))
        self.assertNotEqual(original, signature({"trap": CELLS}, {"trap": ARITHMETIC}))
        self.assertNotEqual(
            signature({"trap": ARITHMETIC}, {"value": {"i64": 0}}, "outcome_kind"),
            signature({"trap": UNINITIALIZED}, {"value": {"i64": 0}}, "outcome_kind"),
        )
        self.assertNotEqual(
            signature({"value": {"bool": True}}, {"value": {"i64": 1}}, "value"),
            signature({"value": {"i64": 0}}, {"value": {"i64": 1}}, "value"),
        )

    def test_wrong_mutant_trap_is_not_a_successful_detection(self):
        # The injected observations test acceptance logic only. They never
        # substitute for the real-driver mutation execution gate.
        mutant_expectations = {
            "add_as_sub": {"value": {"i64": 2}},
            "inclusive_as_strict": {"value": {"bool": False}},
            "branch_inverted": {"value": {"i64": 9}},
            "eager_and": {"trap": ARITHMETIC},
            "eager_or": {"trap": ARITHMETIC},
            "right_before_left": {"trap": ARITHMETIC},
            "wrapping_add": {"value": {"i64": MIN_I64}},
            "floor_division": {"value": {"i64": -3}},
            "floor_remainder": {"value": {"i64": 2}},
        }
        specs = campaign.mutation_witnesses()
        self.assertEqual({item["name"] for item in specs}, set(mutant_expectations))
        controls, mutants = [], []
        for item in specs:
            mutant_expected = mutant_expectations[item["name"]]
            # Independently pin both sides of each executable counterexample.
            self.assertEqual(campaign.oracle(item["mutant"]["program"],
                                             item["mutant"]["calls"][0])["outcome"],
                             mutant_expected)
            for target, case, outcome in ((controls, item["control"], item["expected"]),
                                          (mutants, item["mutant"], mutant_expected)):
                target.append({"id": case["id"], "calls": [{
                    "portable": deepcopy(outcome), "prepared": deepcopy(outcome), "route": "Portable",
                }]})
        poisoned = next(row for row in mutants if row["id"] == "right_before_left")
        poisoned["calls"][0]["prepared"] = {"trap": FUEL}
        metadata = {"sha256": "0" * 64, "typed_jit": False, "os": "synthetic", "arch": "synthetic"}
        with patch.object(campaign, "_observe", side_effect=[(metadata, controls), (metadata, mutants)]):
            report = campaign.mutation_checks("unused-synthetic-driver", timeout=10)
        self.assertEqual(report["summary"]["status"], "failed")
        failed = next(row for row in report["checks"] if row["name"] == "right_before_left")
        self.assertFalse(failed["passed"], "any different trap is not an exact mutant witness")


