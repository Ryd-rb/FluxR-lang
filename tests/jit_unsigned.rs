// These files must be generated by the real emit-native-structured CLI. The
// original generated prepare() checks its embedded, source-bound digest before
// the same kernel is given the owned API's per-invocation route attribution.
macro_rules! emitted_fixture {
    ($name:ident, $export:literal, $file:literal) => {
        #[allow(dead_code, unused_mut, unused_variables)]
        mod $name {
            include!($file);

            pub(super) const TEXT: &str = include_str!($file);

            pub(super) fn owned(
                module: &std::sync::Arc<fluxr::structured::Module>,
            ) -> Result<fluxr::structured::OwnedPreparedAot, fluxr::Error> {
                let _checked_binding = prepare(module)?;
                module.prepare_owned_aot($export, super::aot_identity(module, $export), kernel)
            }
        }
    };
}

