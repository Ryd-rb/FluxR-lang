#[test]
fn unsupported_unsigned_shapes_keep_portable_fallback_and_aot_refusal() {
    let module = Module::compile_compact(
        "v2 (rec U value:u64)
         (pub quotient (x:u64 y:u64) u64 = (/ x y))
         (pub remainder (x:u64 y:u64) u64 = (% x y))
         (pub unsigned_record (r:U) U = r)
         (pub recursive (n:u64) u64 ()
           (if (== n 0u) ((ret 0u)) ((ret (call recursive (- n 1u))))))",
    )
    .unwrap();
    for export in ["quotient", "remainder"] {
        let prepared = module.prepare_call(export).unwrap();
        assert!(module.emit_native_rust(export).is_err());
        for x in [0, 1u64 << 63, u64::MAX] {
            for y in [0, 1, 2, u64::MAX] {
                let expected = if export == "quotient" {
                    x.checked_div(y)
                } else {
                    x.checked_rem(y)
                }
                .map(Value::U64);
                let arguments = [Value::U64(x), Value::U64(y)];
                let (actual, route) = prepared.run_with_route(
                    &[],
                    &arguments,
                    Limits::default(),
                    &mut Workspace::default(),
                );
                assert_rust_result(&actual, &expected, export);
                assert_eq!(route, ExecutionRoute::Portable);
            }
        }
    }
    let original: Arc<[Value]> = [Value::U64(u64::MAX)].into();
    let arguments = [Value::Record(original.clone())];
    let (actual, route) = module
        .prepare_call("unsigned_record")
        .unwrap()
        .run_with_route(
            &[],
            &arguments,
            Limits::default(),
            &mut Workspace::default(),
        );
    let Value::Record(returned) = actual.unwrap() else {
        panic!("record required")
    };
    assert!(Arc::ptr_eq(&returned, &original));
    assert_eq!(route, ExecutionRoute::Portable);
    assert!(module.emit_native_rust("unsigned_record").is_err());
    let (actual, route) = module.prepare_call("recursive").unwrap().run_with_route(
        &[],
        &[Value::U64(3)],
        Limits::default(),
        &mut Workspace::default(),
    );
    assert_eq!(actual, Ok(Value::U64(0)));
    assert_eq!(route, ExecutionRoute::Portable);
    assert!(module.emit_native_rust("recursive").is_err());
    // The checked public frontend has never admitted unsigned bitwise And.
    assert!(Module::compile_compact("v2 (pub bits (x:u64 y:u64) u64 = (&& x y))").is_err());
    let args = (0..33).map(|i| format!(" x{i}:u64")).collect::<String>();
    let wide = Module::compile_compact(&format!("v2 (pub wide ({args}) u64 = x0)")).unwrap();
    let mut values = vec![Value::U64(0); 33];
    values[0] = Value::U64(u64::MAX);
    let (actual, route) = wide.prepare_call("wide").unwrap().run_with_route(
        &[],
        &values,
        Limits::default(),
        &mut Workspace::default(),
    );
    assert_eq!(actual, Ok(Value::U64(u64::MAX)));
    assert_eq!(route, ExecutionRoute::Portable);
    assert!(wide.emit_native_rust("wide").is_err());
}

